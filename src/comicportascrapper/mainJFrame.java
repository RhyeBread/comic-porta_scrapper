    private void mangaJButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_mangaJButtonActionPerformed
        mangaJButton.setEnabled(false);
        statusLabel.setText("Opening series...");
        
        SwingWorker<Void, Void> worker = new SwingWorker<>(){
            @Override
            protected Void doInBackground() throws Exception {
                int index = mangaJComboBox.getSelectedIndex();
                System.out.printf("\n----Opening: %s", links.get(index));

                mangaJFrame chapter = new mangaJFrame();
                chapter.openMangaSite(links.get(index));
                chapter.setLocationRelativeTo(null);
                chapter.setVisible(true);
                return null;
            }
            
            @Override
            protected void done(){
                dispose();
            }
        };
        worker.execute();
    }//GEN-LAST:event_mangaJButtonActionPerformed

