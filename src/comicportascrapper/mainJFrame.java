    public void onStartUp(){
        
        final String url =
                "https://comic-porta.com/series/";
        try{
            final Document document = Jsoup.connect(url).get();
            
            for (Element manga : document.select(
            "h3.title")){
                String title = manga.text();
                String link = manga.select("h3 > a").attr("href");
                
                System.out.printf("Inserting: %s (%s)\n",
                        title, link);
                mangaJComboBox.addItem(title);
                links.add(link);
            }
            
        }
        catch(IOException ex){
        }
    }

